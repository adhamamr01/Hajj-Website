-- ── Secret page links ─────────────────────────────────────────────────────
-- While the site is in "link-only" mode (site.link-only=true) every page is
-- reachable only through an unguessable token. Tokens are NOT seeded here —
-- the backend generates them on startup, so they never live in the repo.

CREATE TABLE page_link (
    id          BIGSERIAL    PRIMARY KEY,
    token       VARCHAR(64)  NOT NULL UNIQUE,
    target_type VARCHAR(20)  NOT NULL CHECK (target_type IN ('PAGE', 'ARTICLE')),
    target_key  VARCHAR(100) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    revoked_at  TIMESTAMPTZ
);

-- Each target has at most one active (non-revoked) link; revoked rows are kept as history.
CREATE UNIQUE INDEX uq_page_link_active_target
    ON page_link (target_type, target_key)
    WHERE revoked_at IS NULL;

-- ── Schema documentation ──────────────────────────────────────────────────

COMMENT ON TABLE page_link IS
    'Secret, unguessable links that give access to a page (or, later, an article) while '
    'the site runs in link-only mode. Resetting a link revokes the row and inserts a new one.';

COMMENT ON COLUMN page_link.token IS
    'URL-safe random token (128 bits, base64url without padding, 22 chars). '
    'Generated by the backend with SecureRandom; this is the secret that appears in /p/{token}.';

COMMENT ON COLUMN page_link.target_type IS
    'What the link opens: PAGE (a site page) or ARTICLE (reserved for a later phase).';

COMMENT ON COLUMN page_link.target_key IS
    'Identifier within target_type. For PAGE: home, journey, meeqat (the Meeqat map) or boundaries (the Sacred Boundaries map).';

COMMENT ON COLUMN page_link.revoked_at IS
    'Set when the link is reset. Null = the link is active. A revoked token resolves to nothing.';
